#!/usr/bin/env python3
"""Turn ql_symbiflow's <top>_iomux.jlink into fpga/qomu_fpga_iomux.c.

The jlink script holds "w4 <addr> <value>" register writes for the S3 IOMUX.
Pad registers (0x40004C00 + 4*pad) are written as given, except that a drive
strength of 2 mA (bits 9:8 = 0) is raised to 4 mA, as in the SDK's pad table
that worked with the SpDE gateware: 2 mA is too weak to drive USB D+/D-.
FBIO_SEL registers (0x40004D80/84) are OR'd so other pads keep their setting.
"""
import sys

IOMUX_PAD0 = 0x40004C00
FBIO_SEL = (0x40004D80, 0x40004D84)
DRV_MASK, DRV_4MA = 0x300, 0x100

src, dst = sys.argv[1], sys.argv[2]
out = ["// Generated by qomu_scheme/gateware/usb2serial/iomux2c.py from the toolchain's",
       "// iomux.jlink (open toolchain): pad setup the FPGA bitstream expects.",
       "#include <stdint.h>", "", "void qomu_fpga_pads_init(void)", "{"]
n = 0
for line in open(src):
    f = line.split()
    if len(f) < 3 or f[0] != "w4":
        continue
    addr, val = int(f[1], 16), int(f[2], 16)
    if addr in FBIO_SEL:
        out.append(f"    *(volatile uint32_t *)0x{addr:08X} |= 0x{val:08X};   /* FBIO_SEL */")
    else:
        note = ""
        if (val & DRV_MASK) == 0:
            val |= DRV_4MA
            note = ", 4 mA"
        pad = (addr - IOMUX_PAD0) // 4
        out.append(f"    *(volatile uint32_t *)0x{addr:08X}  = 0x{val:08X};   /* PAD {pad}{note} */")
    n += 1
out.append("}")
open(dst, "w").write("\n".join(out) + "\n")
print(f"== install: wrote {dst.split('/')[-1]} ({n} register writes)")
